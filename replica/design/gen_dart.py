#!/usr/bin/env python3
"""Generate the Flutter design tokens from tokens.json + tokens.dark.json.

    python3 -I replica/design/gen_dart.py replica/design app/lib/design/tokens.g.dart

Role names stay; /replica-brand only edits the JSON values and reruns this.
"""
import json
import re
import sys
from pathlib import Path


def camel(name):
    parts = re.split(r"[-_]", name)
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def argb(hex_):
    h = hex_.lstrip("#")
    return "Color(0xFF%s)" % h.upper()


def main(src_dir, out):
    src = Path(src_dir)
    light = json.loads((src / "tokens.json").read_text(encoding="utf-8"))
    dark = json.loads((src / "tokens.dark.json").read_text(encoding="utf-8"))
    roles = list(light["color"].keys())
    missing = set(roles) ^ set(dark["color"].keys())
    if missing:
        sys.exit("light and dark roles differ: %s" % sorted(missing))

    L = []
    w = L.append
    w("// GENERATED by replica/design/gen_dart.py from tokens.json. Do not edit by hand.")
    w("// ignore_for_file: public_member_api_docs")
    w("import 'package:flutter/material.dart';")
    w("")
    w("@immutable")
    w("class AppColors extends ThemeExtension<AppColors> {")
    w("  const AppColors({")
    for r in roles:
        w("    required this.%s," % camel(r))
    w("  });")
    w("")
    for r in roles:
        w("  final Color %s;" % camel(r))
    w("")
    for name, t in (("light", light), ("dark", dark)):
        w("  static const %s = AppColors(" % name)
        for r in roles:
            w("    %s: %s," % (camel(r), argb(t["color"][r])))
        w("  );")
        w("")
    w("  @override")
    w("  AppColors copyWith({%s}) => AppColors(" % ", ".join("Color? %s" % camel(r) for r in roles))
    for r in roles:
        c = camel(r)
        w("    %s: %s ?? this.%s," % (c, c, c))
    w("  );")
    w("")
    w("  @override")
    w("  AppColors lerp(ThemeExtension<AppColors>? other, double t) {")
    w("    if (other is! AppColors) return this;")
    w("    return AppColors(")
    for r in roles:
        c = camel(r)
        w("      %s: Color.lerp(%s, other.%s, t)!," % (c, c, c))
    w("    );")
    w("  }")
    w("}")
    w("")

    font = light["font"]
    w("abstract final class AppFont {")
    w("  static const family = '%s';" % font["sans"])
    w("  static const fallback = <String>[%s];" % ", ".join("'%s'" % f for f in font["fallback"]))
    w("}")
    w("")
    w("abstract final class AppType {")
    weights = {400: "w400", 500: "w500", 600: "w600", 700: "w700", 800: "w800"}
    for k, v in light["type"].items():
        w("  static const %s = TextStyle(fontFamily: AppFont.family, fontFamilyFallback: AppFont.fallback, "
          "fontSize: %d, height: %s, fontWeight: FontWeight.%s);"
          % (camel(k), v["size"], round(v["line"] / v["size"], 4), weights[v["weight"]]))
    w("}")
    w("")
    w("abstract final class AppSpace {")
    for v in light["space"]:
        w("  static const double s%d = %d;" % (v, v))
    w("}")
    w("")
    w("abstract final class AppRadius {")
    for k, v in light["radius"].items():
        w("  static const double %s = %d;" % (camel(k), v))
    w("}")
    w("")
    w("abstract final class AppLayout {")
    for k, v in light["layout"].items():
        w("  static const double %s = %d;" % (camel(k), v))
    w("}")
    w("")
    w("abstract final class AppMotion {")
    m = light["motion"]
    w("  static const fast = Duration(milliseconds: %d);" % int(m["fast"].rstrip("ms")))
    w("  static const base = Duration(milliseconds: %d);" % int(m["base"].rstrip("ms")))
    nums = re.findall(r"[\d.]+", m["ease"])
    w("  static const ease = Cubic(%s);" % ", ".join(nums))
    w("}")
    w("")
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text("\n".join(L), encoding="utf-8")
    print("wrote %s (%d colour roles)" % (out, len(roles)))


if __name__ == "__main__":
    main(*sys.argv[1:3])
